import sys

from playwright.sync_api import sync_playwright

sys.path.insert(0, "scratch")
from chrome_helper import PORT, ensure_chrome

with sync_playwright() as p:
    ensure_chrome()
    browser = p.chromium.connect_over_cdp(f"http://127.0.0.1:{PORT}")
    page = browser.contexts[0].pages[0]

    # Check if timer modal is present first
    st_btn = page.locator("button:has-text('Start timer')")
    if st_btn.count() > 0 and st_btn.first.is_visible():
        box = st_btn.first.bounding_box()
        if box:
            print("Dismissing timer modal before toggle...")
            page.mouse.click(box["x"] + box["width"] / 2, box["y"] + box["height"] / 2)
            page.wait_for_timeout(1000)

    # Click the Feedback toggle button
    fb_btn = page.locator("button[aria-label='Feedback']")
    print("Found feedback button:", fb_btn.count())
    if fb_btn.count() > 0:
        fb_btn.first.click()
        page.wait_for_timeout(1000)

    # Check if timer modal appeared again
    if st_btn.count() > 0 and st_btn.first.is_visible():
        box = st_btn.first.bounding_box()
        if box:
            print("Dismissing timer modal after toggle...")
            page.mouse.click(box["x"] + box["width"] / 2, box["y"] + box["height"] / 2)
            page.wait_for_timeout(1000)

    page.screenshot(path="scratch/feedback_opened_clean.png")
    print("Saved scratch/feedback_opened_clean.png")
